"""`network-analyser role-snippet ios-xe|nx-os [--username NAME] [--tacacs]` (stories 167-173).

Prints the Device Role that gives the tool's dedicated account exactly the commands on the
allow-list (ADR 0005), generated from that same compiled-in list. It only prints: no
device is contacted and nothing is written, so no lock or data folder is needed.

Exit codes: 0 printed; 2 refused (a username that does not fit).
"""

import argparse
from typing import Final

from network_analyser import platforms
from network_analyser._version import __version__
from network_analyser.cli.exit_codes import ExitCode
from network_analyser.cli.parser import PROG
from network_analyser.cli.run_folder import refuse
from network_analyser.records import Platform

_PLATFORMS: Final = {"ios-xe": Platform.IOS_XE, "nx-os": Platform.NX_OS}


def role_snippet(args: argparse.Namespace) -> ExitCode:
    """Print the Device Role for the chosen Platform, local or TACACS+ form."""
    username: str | None = args.username
    if username is not None:
        problem = platforms.role_username_problem(username)
        if problem is not None:  # the reason never quotes the name
            refuse(args.command, f"{problem}.")
            return ExitCode.REFUSED
    platform = _PLATFORMS[args.platform]
    text = platforms.role_snippet(platform, username, tacacs=args.tacacs)
    asked = " ".join(
        [PROG, args.command, args.platform]
        + ([] if username is None else ["--username", username])
        + (["--tacacs"] if args.tacacs else [])
    )
    print(f"! Generated by network-analyser {__version__} from its allow-list: {asked}")
    print(text, end="")
    return ExitCode.CLEAN
